import { useEffect, useState } from "react";
import { api } from "../api";
import { Link } from "../components/Link";

interface Site {
  app_name: string;
  operator: string | null;
  contact_email: string | null;
  governing_law: string | null;
  terms_version: string;
  price_cents: number;
  monthly_cap_usd: number;
}

export type LegalDoc = "terms" | "privacy" | "refunds" | "copyright";

const TITLES: Record<LegalDoc, string> = {
  terms: "Terms of Service",
  privacy: "Privacy Policy",
  refunds: "Subscription & Refund Policy",
  copyright: "Copyright & Takedown Policy",
};

function useSite(): Site | null {
  const [site, setSite] = useState<Site | null>(null);
  useEffect(() => {
    api<Site>("/site")
      .then(setSite)
      .catch(() => setSite(null));
  }, []);
  return site;
}

export function LegalPage({ doc }: { doc: LegalDoc }) {
  const site = useSite();
  if (!site) return <p className="muted">Loading…</p>;
  const ctx = {
    app: site.app_name,
    operator: site.operator ?? `the individual who runs ${site.app_name}`,
    contact: site.contact_email ? <a href={`mailto:${site.contact_email}`}>{site.contact_email}</a> : <strong>[contact email not configured]</strong>,
    law: site.governing_law ?? "the laws of the place where the operator lives",
    price: `$${(site.price_cents / 100).toFixed(site.price_cents % 100 ? 2 : 0)}`,
    cap: `$${site.monthly_cap_usd}`,
    updated: site.terms_version,
  };
  return (
    <article className="legal">
      <h1>{TITLES[doc]}</h1>
      <p className="muted small">Last updated {ctx.updated}</p>
      {doc === "terms" && <Terms {...ctx} />}
      {doc === "privacy" && <Privacy {...ctx} />}
      {doc === "refunds" && <Refunds {...ctx} />}
      {doc === "copyright" && <Copyright {...ctx} />}
      <nav className="legal-nav" aria-label="Policies">
        <Link href="/terms">Terms</Link> · <Link href="/privacy">Privacy</Link> · <Link href="/refunds">Refunds</Link> ·{" "}
        <Link href="/copyright">Copyright</Link>
      </nav>
    </article>
  );
}

